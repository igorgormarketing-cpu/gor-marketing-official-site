// Authentic 3D Lego Mesh Generator based on official LDraw/Rebrickable dimensions
window.createLegoPart3D = function(partDef, colorHex) {
  const group = new THREE.Group();
  const c = colorHex !== undefined ? colorHex : (partDef.defaultColor || 0xdc2626);
  
  const studUnit = 0.8; // 1 stud = 0.8 Three.js units (~8mm)
  const plateHeight = 0.32; // 1 plate = 0.32 units (~3.2mm)
  const brickHeight = plateHeight * (partDef.heightUnits || 3);
  
  const width = partDef.studsL * studUnit;
  const depth = partDef.studsW * studUnit;
  
  const mat = new THREE.MeshStandardMaterial({
    color: c,
    roughness: 0.22,
    metalness: 0.08
  });

  const studGeom = new THREE.CylinderGeometry(0.24, 0.24, 0.14, 16);
  const studMat = new THREE.MeshStandardMaterial({
    color: c,
    roughness: 0.22,
    metalness: 0.08
  });

  if (partDef.isFence) {
    // Ornamental Fence 1x4x2
    const postGeom = new THREE.BoxGeometry(0.2, brickHeight, 0.2);
    const railGeom = new THREE.BoxGeometry(width, 0.16, 0.16);
    const barGeom = new THREE.CylinderGeometry(0.06, 0.06, brickHeight - 0.3, 8);

    const postL = new THREE.Mesh(postGeom, mat);
    postL.position.set(-width / 2 + 0.1, brickHeight / 2, 0);
    group.add(postL);

    const postR = new THREE.Mesh(postGeom, mat);
    postR.position.set(width / 2 - 0.1, brickHeight / 2, 0);
    group.add(postR);

    const railTop = new THREE.Mesh(railGeom, mat);
    railTop.position.set(0, brickHeight - 0.1, 0);
    group.add(railTop);

    const railBot = new THREE.Mesh(railGeom, mat);
    railBot.position.set(0, 0.1, 0);
    group.add(railBot);

    for (let i = -1.2; i <= 1.2; i += 0.6) {
      const bar = new THREE.Mesh(barGeom, mat);
      bar.position.set(i, brickHeight / 2, 0);
      group.add(bar);
    }
  } else if (partDef.hasGlass) {
    // Window Frame with Glass
    const frameGeom = new THREE.BoxGeometry(width, brickHeight, depth);
    const frame = new THREE.Mesh(frameGeom, mat);
    frame.position.y = brickHeight / 2;
    group.add(frame);

    const glassMat = new THREE.MeshPhysicalMaterial({
      color: 0xbae6fd,
      transparent: true,
      opacity: 0.55,
      roughness: 0.05,
      transmission: 0.9
    });
    const glassGeom = new THREE.BoxGeometry(width - 0.3, brickHeight - 0.4, depth * 0.3);
    const glass = new THREE.Mesh(glassGeom, glassMat);
    glass.position.y = brickHeight / 2;
    group.add(glass);
  } else if (partDef.isArch) {
    // Arch 1x4
    const archShape = new THREE.Shape();
    archShape.moveTo(-width / 2, 0);
    archShape.lineTo(width / 2, 0);
    archShape.lineTo(width / 2, brickHeight);
    archShape.lineTo(-width / 2, brickHeight);
    archShape.closePath();

    const hole = new THREE.Path();
    hole.absarc(0, 0, (width / 2) - 0.25, 0, Math.PI, false);
    archShape.holes.push(hole);

    const extrudeSettings = { depth: depth, bevelEnabled: true, bevelSegments: 2, steps: 1, bevelSize: 0.02, bevelThickness: 0.02 };
    const archGeom = new THREE.ExtrudeGeometry(archShape, extrudeSettings);
    archGeom.center();
    const arch = new THREE.Mesh(archGeom, mat);
    arch.position.y = brickHeight / 2;
    group.add(arch);
  } else if (partDef.slopeDeg > 0) {
    // Slope 45 / 33
    const slopeShape = new THREE.Shape();
    slopeShape.moveTo(-width / 2, 0);
    slopeShape.lineTo(width / 2, 0);
    slopeShape.lineTo(width / 2, 0.2);
    slopeShape.lineTo(-width / 2, brickHeight);
    slopeShape.closePath();

    const extrudeSettings = { depth: depth, bevelEnabled: true, bevelSegments: 2, steps: 1, bevelSize: 0.02, bevelThickness: 0.02 };
    const slopeGeom = new THREE.ExtrudeGeometry(slopeShape, extrudeSettings);
    slopeGeom.center();
    const slope = new THREE.Mesh(slopeGeom, mat);
    slope.position.y = brickHeight / 2;
    group.add(slope);
  } else if (partDef.isRound) {
    // Round Cylinder Brick
    const cylGeom = new THREE.CylinderGeometry(width / 2, width / 2, brickHeight, 24);
    const cyl = new THREE.Mesh(cylGeom, mat);
    cyl.position.y = brickHeight / 2;
    group.add(cyl);

    const stud = new THREE.Mesh(studGeom, studMat);
    stud.position.set(0, brickHeight + 0.07, 0);
    group.add(stud);
    return group;
  } else {
    // Standard Brick or Plate Box
    const bodyGeom = new THREE.BoxGeometry(width, brickHeight, depth);
    const body = new THREE.Mesh(bodyGeom, mat);
    body.position.y = brickHeight / 2;
    body.castShadow = true;
    body.receiveShadow = true;
    group.add(body);

    if (!partDef.isTile) {
      // Add studs on top
      const startX = -(partDef.studsL - 1) * studUnit / 2;
      const startZ = -(partDef.studsW - 1) * studUnit / 2;
      for (let ix = 0; ix < partDef.studsL; ix++) {
        for (let iz = 0; iz < partDef.studsW; iz++) {
          const stud = new THREE.Mesh(studGeom, studMat);
          stud.position.set(startX + (ix * studUnit), brickHeight + 0.07, startZ + (iz * studUnit));
          stud.castShadow = true;
          group.add(stud);
        }
      }
    }
  }

  group.userData = {
    partId: partDef.id,
    name: partDef.name,
    heName: partDef.heName,
    width: width,
    depth: depth,
    height: brickHeight
  };

  return group;
};
